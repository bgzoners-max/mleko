import 'dart:io';

/// Tool za automatizaciju i analizu squasha migracija u jedan snapshot fajl (`supabase/schema.sql`).
///
/// Upotreba:
///   dart run tool/squash_migrations.dart --cutoff=20261021093000 --dry-run
///   dart run tool/squash_migrations.dart --cutoff=20261021093000 --apply
///   dart run tool/squash_migrations.dart --generate-schema-snapshot
void main(List<String> args) {
  final migrationsDir = Directory('supabase/migrations');
  if (!migrationsDir.existsSync()) {
    stderr.writeln('ERROR: supabase/migrations directory does not exist.');
    exitCode = 1;
    return;
  }

  final files = migrationsDir
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.sql'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  stdout.writeln('Found ${files.length} total migration files in supabase/migrations/');

  bool isSnapshotOnly = args.contains('--generate-schema-snapshot');
  bool isApply = args.contains('--apply');
  String? cutoff;

  for (final arg in args) {
    if (arg.startsWith('--cutoff=')) {
      cutoff = arg.substring('--cutoff='.length).trim();
    }
  }

  // Ako nije naveden cutoff, koristi podrazumevani cutoff pre današnjih izmena (20261021093000)
  cutoff ??= '20261021093000';

  final toSquash = <File>[];
  final toKeep = <File>[];

  for (final file in files) {
    final fileName = file.uri.pathSegments.last;
    final timestamp = fileName.split('_').first;
    if (timestamp.compareTo(cutoff) <= 0) {
      toSquash.add(file);
    } else {
      toKeep.add(file);
    }
  }

  stdout.writeln('---');
  stdout.writeln('Cutoff version: $cutoff');
  stdout.writeln('Migrations to squash into baseline: ${toSquash.length}');
  stdout.writeln('Active incremental migrations to keep: ${toKeep.length}');
  stdout.writeln('---');

  // Generisanje konsolidovanog schema.sql snapshot-a
  final snapshotFile = File('supabase/schema.sql');
  final buffer = StringBuffer();
  buffer.writeln('-- =============================================================================');
  buffer.writeln('-- CONSOLIDATED SUPABASE SCHEMA SNAPSHOT');
  buffer.writeln('-- Generated by: tool/squash_migrations.dart');
  buffer.writeln('-- Cutoff migration: $cutoff');
  buffer.writeln('-- Total squashed migrations: ${toSquash.length}');
  buffer.writeln('-- Generated at: ${DateTime.now().toIso8601String()}');
  buffer.writeln('-- =============================================================================');
  buffer.writeln();

  for (final file in toSquash) {
    final fileName = file.uri.pathSegments.last;
    buffer.writeln('-- >>> BEGIN MIGRATION: $fileName <<<');
    buffer.writeln(file.readAsStringSync().trim());
    buffer.writeln();
    buffer.writeln('-- >>> END MIGRATION: $fileName <<<');
    buffer.writeln();
  }

  snapshotFile.writeAsStringSync(buffer.toString());
  stdout.writeln('SUCCESS: Generated consolidated schema snapshot at ${snapshotFile.path} (${(snapshotFile.lengthSync() / 1024).toStringAsFixed(1)} KB).');

  if (isSnapshotOnly) {
    return;
  }

  if (!isApply) {
    stdout.writeln();
    stdout.writeln('[DRY RUN] No files were moved or deleted.');
    stdout.writeln('To archive squashed migrations and replace with baseline, run:');
    stdout.writeln('  dart run tool/squash_migrations.dart --cutoff=$cutoff --apply');
    stdout.writeln();
    stdout.writeln('Remote migration repair commands for staging and production:');
    stdout.writeln('  npx supabase migration repair --status reverted <versions>');
    stdout.writeln('  npx supabase migration repair --status applied $cutoff');
    return;
  }

  // Apply: arhiviranje
  final archiveDir = Directory('supabase/migrations_archive');
  if (!archiveDir.existsSync()) {
    archiveDir.createSync(recursive: true);
  }

  stdout.writeln('Moving ${toSquash.length} migrations to ${archiveDir.path}...');
  for (final file in toSquash) {
    final fileName = file.uri.pathSegments.last;
    final dest = File('${archiveDir.path}/$fileName');
    file.renameSync(dest.path);
  }

  final baselineMigration = File('supabase/migrations/${cutoff}_baseline_schema.sql');
  snapshotFile.copySync(baselineMigration.path);
  stdout.writeln('Created baseline migration: ${baselineMigration.path}');
  stdout.writeln('Squash complete! Active migrations in supabase/migrations/: ${toKeep.length + 1}');
}
