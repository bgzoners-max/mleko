import 'dart:io';

/// Tool za automatizaciju i analizu squasha migracija u jedan snapshot fajl (`supabase/schema.sql`).
///
/// Upotreba:
///   dart run tool/squash_migrations.dart --cutoff=20261021093000 --dry-run
///   dart run tool/squash_migrations.dart --cutoff=20261021093000 --apply
///   dart run tool/squash_migrations.dart --generate-schema-snapshot
///   dart run tool/squash_migrations.dart --check
///
/// `--check` ne piše ništa na disk: regeneriše očekivani sadržaj snapshot-a u
/// memoriji i poređenje ga sa commitovanim `supabase/schema.sql` (ignorišući
/// vremensku oznaku `-- Generated at` i CRLF razlike). Koristi se u CI-u kao
/// drift guard — pad signalizira da je snapshot ručno izmenjen ili da je
/// pre-cutoff migracija izmenjena nakon generisanja.
///
/// Snapshot se upisuje na disk **samo** uz `--generate-schema-snapshot` ili
/// `--apply`; `--dry-run` nema nikakve nuspojave (ne menja ni jedan fajl).
void main(List<String> args) {
  final migrationsDir = Directory('supabase/migrations');
  if (!migrationsDir.existsSync()) {
    stderr.writeln('ERROR: supabase/migrations directory does not exist.');
    exitCode = 1;
    return;
  }

  final files = migrationsDir
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.sql'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  stdout.writeln('Found ${files.length} total migration files in supabase/migrations/');

  final bool isSnapshotOnly = args.contains('--generate-schema-snapshot');
  final bool isCheck = args.contains('--check');
  final bool isApply = args.contains('--apply');
  String? cutoff;

  for (final arg in args) {
    if (arg.startsWith('--cutoff=')) {
      cutoff = arg.substring('--cutoff='.length).trim();
    }
  }

  // Ako nije naveden cutoff, koristi podrazumevani cutoff pre današnjih izmena (20261021093000)
  cutoff ??= '20261021093000';

  final toSquash = <File>[];
  final toKeep = <File>[];

  for (final file in files) {
    final fileName = file.uri.pathSegments.last;
    final timestamp = fileName.split('_').first;
    if (timestamp.compareTo(cutoff) <= 0) {
      toSquash.add(file);
    } else {
      toKeep.add(file);
    }
  }

  stdout
    ..writeln('---')
    ..writeln('Cutoff version: $cutoff')
    ..writeln('Migrations to squash into baseline: ${toSquash.length}')
    ..writeln('Active incremental migrations to keep: ${toKeep.length}')
    ..writeln('---');

  // Generisanje konsolidovanog schema.sql snapshot-a
  final snapshotFile = File('supabase/schema.sql');
  final buffer = StringBuffer()
    ..writeln('-- =============================================================================')
    ..writeln('-- CONSOLIDATED SUPABASE SCHEMA SNAPSHOT')
    ..writeln('-- Generated by: tool/squash_migrations.dart')
    ..writeln('-- Cutoff migration: $cutoff')
    ..writeln('-- Total squashed migrations: ${toSquash.length}')
    ..writeln('-- Generated at: ${DateTime.now().toIso8601String()}')
    ..writeln('-- =============================================================================')
    ..writeln();

  for (final file in toSquash) {
    final fileName = file.uri.pathSegments.last;
    buffer
      ..writeln('-- >>> BEGIN MIGRATION: $fileName <<<')
      ..writeln(file.readAsStringSync().trim())
      ..writeln()
      ..writeln('-- >>> END MIGRATION: $fileName <<<')
      ..writeln();
  }

  final snapshotContent = buffer.toString();

  // Drift guard (CI): provera sinhronizacije bez pisanja na disk.
  if (isCheck) {
    _verifySnapshotInSync(snapshotFile, snapshotContent, cutoff);
    return;
  }

  // Snapshot se upisuje samo pri eksplicitnoj regeneraciji ili apply-u —
  // --dry-run ostaje bez nuspojava po fajlove na disku.
  if (isSnapshotOnly || isApply) {
    snapshotFile.writeAsStringSync(snapshotContent);
    stdout.writeln('SUCCESS: Generated consolidated schema snapshot at ${snapshotFile.path} (${(snapshotFile.lengthSync() / 1024).toStringAsFixed(1)} KB).');
  }

  if (isSnapshotOnly) {
    return;
  }

  if (!isApply) {
    stdout
      ..writeln()
      ..writeln('[DRY RUN] No files were moved or deleted.')
      ..writeln('To archive squashed migrations and replace with baseline, run:')
      ..writeln('  dart run tool/squash_migrations.dart --cutoff=$cutoff --apply')
      ..writeln()
      ..writeln('Remote migration repair commands for staging and production:')
      ..writeln('  npx supabase migration repair --status reverted <versions>')
      ..writeln('  npx supabase migration repair --status applied $cutoff');
    return;
  }

  // Apply: arhiviranje
  final archiveDir = Directory('supabase/migrations_archive');
  if (!archiveDir.existsSync()) {
    archiveDir.createSync(recursive: true);
  }

  stdout.writeln('Moving ${toSquash.length} migrations to ${archiveDir.path}...');
  for (final file in toSquash) {
    final fileName = file.uri.pathSegments.last;
    final dest = File('${archiveDir.path}/$fileName');
    file.renameSync(dest.path);
  }

  final baselineMigration = File('supabase/migrations/${cutoff}_baseline_schema.sql');
  snapshotFile.copySync(baselineMigration.path);
  stdout
    ..writeln('Created baseline migration: ${baselineMigration.path}')
    ..writeln('Squash complete! Active migrations in supabase/migrations/: ${toKeep.length + 1}');
}

/// Poredi ocekivani (regenerisani) sadrzaj snapshot-a sa commitovanim
/// `supabase/schema.sql`. Normalizuje CRLF na LF i ignorise vremensku oznaku
/// `-- Generated at` (jedina linija koja se menja pri svakoj regeneraciji).
/// Postavlja `exitCode = 1` na drift, sa jasnim uputstvom za popravku.
void _verifySnapshotInSync(File snapshotFile, String expected, String cutoff) {
  if (!snapshotFile.existsSync()) {
    stderr
      ..writeln('ERROR: ${snapshotFile.path} does not exist.')
      ..writeln('Generate it with: dart run tool/squash_migrations.dart --generate-schema-snapshot');
    exitCode = 1;
    return;
  }

  String normalize(String source) {
    return source
        .replaceAll('\r\n', '\n')
        .split('\n')
        .where((line) => !line.startsWith('-- Generated at'))
        .join('\n')
        .trim();
  }

  final committed = snapshotFile.readAsStringSync();
  if (normalize(committed) == normalize(expected)) {
    stdout.writeln('OK: supabase/schema.sql is in sync with migrations up to cutoff $cutoff.');
    return;
  }

  stderr
    ..writeln('DRIFT DETECTED: supabase/schema.sql ne odgovara trenutnim migracijama do cutoff-a $cutoff.')
    ..writeln('Uzrok je rucna izmena snapshot-a ili izmena pre-cutoff migracije nakon generisanja.')
    ..writeln('Popravka (regeneracija): dart run tool/squash_migrations.dart --generate-schema-snapshot');
  exitCode = 1;
}
